#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn stdlib_header_roots_sorted_unique() {
		for pair in STDLIB_HEADER_ROOTS.windows(2) {
			assert!(
				pair[0] < pair[1],
				"expected sorted unique header roots, got `{}` before `{}`",
				pair[0],
				pair[1]
			);
		}
	}

	#[test]
	fn libc_functions_sorted_unique() {
		for pair in LIBC_FUNCTIONS.windows(2) {
			assert!(
				pair[0] < pair[1],
				"expected sorted unique libc list, got `{}` before `{}`",
				pair[0],
				pair[1]
			);
		}
	}

	#[test]
	fn libc_functions_are_language_contract() {
		for name in [
			b"malloc".as_slice(),
			b"free",
			b"printf",
			b"memcpy",
			b"strlen",
			b"open",
			b"close",
			b"pthread_create",
		] {
			assert!(is_libc_function(name));
		}
		assert!(!is_libc_function(b"listCreate"));
		assert!(!is_libc_function(b"zmalloc"));
	}
}
